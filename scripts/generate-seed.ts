// Generates supabase/seed.sql from the Milestone 1 sample data (src/lib/data/sample).
// Run: pnpm seed:generate   (node --experimental-strip-types scripts/generate-seed.ts)
// The SQL is idempotent: rows are upserted by their natural keys (slug, github_id, ...),
// so it can be re-run safely. Stats and rankings use the capture time of the sample data,
// never "now", so nothing is presented as fresher than it is.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { sampleCategories } from "../src/lib/data/sample/categories.ts";
import { sampleRepositories } from "../src/lib/data/sample/repositories.ts";
import { openseoContent } from "../src/lib/data/sample/content/openseo.ts";
import { rankRepositories } from "../src/lib/ranking.ts";

const DATA_AS_OF = "2026-11-24T23:43:00Z";
const CONTENT = { openseo: openseoContent };

// Strings with an apostrophe are dollar-quoted instead of using '' escapes (see j below).
const STAG = "$" + "t" + "$";
const q = (v: string | null | undefined) => {
  if (v == null) return "null";
  if (!v.includes("'")) return `'${v}'`;
  if (v.includes(STAG)) throw new Error("string contains the dollar-quote tag");
  return `${STAG}${v}${STAG}`;
};
// JSON goes in dollar quotes, pretty-printed, so the file survives copy-paste into the
// Supabase SQL Editor (no doubled quotes to mangle, no 30 KB single lines).
const TAG = "$" + "json" + "$";
const j = (v: unknown) => {
  const json = JSON.stringify(v, null, 1);
  if (json.includes(TAG)) throw new Error("JSON contains the dollar-quote tag");
  return `${TAG}${json}${TAG}::jsonb`;
};
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const repoId = (slug: string) => `(select id from public.repositories where slug = ${q(slug)})`;

const out: string[] = [
  "-- Generated by scripts/generate-seed.ts. Do not edit by hand.",
  `-- Sample data captured ${DATA_AS_OF} from the GitHub API; editorial fields written for Milestone 1.`,
  "",
  "-- categories",
];

sampleCategories.forEach((c, i) => {
  out.push(
    `insert into public.categories (slug, name, description, icon, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${i}) ` +
      `on conflict (slug) do update set name = excluded.name, description = excluded.description, icon = excluded.icon, sort_order = excluded.sort_order;`,
  );
});

// Repositories, their categories and the first stats row, as one JSON payload + set-based SQL
// (compact enough to apply through the Supabase MCP in a single call).
const repoRows = sampleRepositories.map((r) => ({
  github_id: r.githubId, owner: r.owner, name: r.name, full_name: r.fullName, slug: r.slug, github_url: r.githubUrl,
  homepage_url: r.homepageUrl, description: r.description, summary: r.summary, kind: r.kind, primary_language: r.primaryLanguage,
  license_key: r.licenseKey, topics: r.topics, stars: r.stars, forks: r.forks, open_issues: r.openIssues, avatar_url: r.avatarUrl,
  is_archived: r.isArchived, created_at_github: r.createdAtGithub, updated_at_github: r.updatedAtGithub, last_pushed_at: r.lastPushedAt,
  stats_checked_at: r.statsCheckedAt ?? DATA_AS_OF, published_at: r.publishedAt, status: r.status, difficulty: r.difficulty,
  featured: r.featured, categories: r.categorySlugs,
}));
const cols = [
  "github_id", "owner", "name", "full_name", "slug", "github_url", "homepage_url", "description", "summary", "kind",
  "primary_language", "license_key", "topics", "stars", "forks", "open_issues", "avatar_url", "is_archived", "created_at_github",
  "updated_at_github", "last_pushed_at", "stats_checked_at", "published_at", "status", "difficulty", "featured",
];
out.push(
  "",
  "-- repositories",
  `create temporary table seed_repos on commit drop as select * from jsonb_to_recordset(${j(repoRows)}) as x(github_id bigint, owner text, name text, full_name text, slug text, github_url text, homepage_url text, description text, summary text, kind public.repo_kind, primary_language text, license_key text, topics text[], stars int, forks int, open_issues int, avatar_url text, is_archived boolean, created_at_github timestamptz, updated_at_github timestamptz, last_pushed_at timestamptz, stats_checked_at timestamptz, published_at timestamptz, status public.repo_status, difficulty public.difficulty_level, featured boolean, categories text[]);`,
  `insert into public.repositories (${cols.join(", ")}) select ${cols.join(", ")} from seed_repos ` +
    `on conflict (github_id) do update set ${cols.filter((c) => c !== "github_id").map((c) => `${c} = excluded.${c}`).join(", ")};`,
  `insert into public.repository_categories (repository_id, category_id, is_primary) select r.id, c.id, x.ord = 1 from seed_repos s cross join lateral unnest(s.categories) with ordinality as x(slug, ord) join public.repositories r on r.github_id = s.github_id join public.categories c on c.slug = x.slug on conflict (repository_id, category_id) do update set is_primary = excluded.is_primary;`,
  `insert into public.repository_stats (repository_id, recorded_at, recorded_on, stars, forks, open_issues) select r.id, s.stats_checked_at, (s.stats_checked_at at time zone 'utc')::date, s.stars, s.forks, s.open_issues from seed_repos s join public.repositories r on r.github_id = s.github_id on conflict (repository_id, recorded_on) do nothing;`,
);

out.push("", "-- product-page content");
for (const [slug, c] of Object.entries(CONTENT)) {
  const id = repoId(slug);
  const installMeta = {
    verificationNote: c.install.verificationNote,
    supportedOs: c.install.supportedOs,
    firstRun: c.install.firstRun,
    sourceUrl: c.install.sourceUrl,
  };
  out.push(
    `insert into public.repository_content (repository_id, sixty_seconds, features, strengths, limitations, use_cases, costs, troubleshooting, source_urls, source_commit_sha, last_reviewed_at, hero_commands, overview, best_for, facts, install_meta) values (` +
      [id, j(c.sixtySeconds), j(c.features), arr(c.strengths), arr(c.limitations), j(c.useCases), j(c.costs), j(c.troubleshooting),
        arr(c.sourceUrls), q(c.sourceCommitSha), q(c.lastReviewedAt), j(c.heroCommands), arr(c.overview), arr(c.bestFor), j(c.facts), j(installMeta)].join(", ") +
      `) on conflict (repository_id) do update set sixty_seconds = excluded.sixty_seconds, features = excluded.features, strengths = excluded.strengths, limitations = excluded.limitations, use_cases = excluded.use_cases, costs = excluded.costs, troubleshooting = excluded.troubleshooting, source_urls = excluded.source_urls, source_commit_sha = excluded.source_commit_sha, last_reviewed_at = excluded.last_reviewed_at, hero_commands = excluded.hero_commands, overview = excluded.overview, best_for = excluded.best_for, facts = excluded.facts, install_meta = excluded.install_meta;`,
  );
  c.install.guides.forEach((g, i) => {
    out.push(
      `insert into public.installation_guides (repository_id, operating_system, method, label, sort_order, prerequisites, instructions, environment, expected_output, verification_status, source_url, source_commit_sha, last_reviewed_at, status) values (` +
        [id, `${q(g.os)}::os_target`, q(g.method), q(g.label), String(i), j(c.install.prerequisites), j(g.steps), j(c.install.environment),
          q(c.install.expectedOutput), `${q(c.install.verification)}::verification_status`, q(c.install.sourceUrl), q(c.sourceCommitSha),
          q(c.lastReviewedAt), "'published'::content_status"].join(", ") +
        `) on conflict (repository_id, operating_system, method) do update set label = excluded.label, sort_order = excluded.sort_order, prerequisites = excluded.prerequisites, instructions = excluded.instructions, environment = excluded.environment, expected_output = excluded.expected_output, verification_status = excluded.verification_status, source_url = excluded.source_url, source_commit_sha = excluded.source_commit_sha, last_reviewed_at = excluded.last_reviewed_at, status = excluded.status;`,
    );
  });
  const t = c.tutorial;
  const tSlug = t.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  out.push(
    `insert into public.tutorials (repository_id, title, slug, content, status, source_url) values (${id}, ${q(t.title)}, ${q(tSlug)}, ${j({ useCase: t.useCase, setup: t.setup, steps: t.steps, expected: t.expected, nextSteps: t.nextSteps })}, 'published', ${q(t.sourceUrl)}) ` +
      `on conflict (repository_id, slug) do update set title = excluded.title, content = excluded.content, status = excluded.status, source_url = excluded.source_url;`,
  );
}

// First all-time ranking snapshot: global plus one per category. Growth/docs are unknown,
// so rankRepositories drops those signals; star_growth and previous_rank stay null.
out.push("", "-- ranking snapshot (all_time, v1); replaced if this capture time was seeded before");
const published = sampleRepositories.filter((r) => r.status === "published");
const pools: [string | null, typeof published][] = [
  [null, published],
  ...sampleCategories.map((c) => [c.slug, published.filter((r) => r.categorySlugs.includes(c.slug))] as [string, typeof published]),
];
const rankingRows = pools.flatMap(([cat, pool]) =>
  rankRepositories(
    pool.map((r) => ({ id: r.id, stars: r.stars, forks: r.forks, lastPushedAt: r.lastPushedAt })),
    new Date(DATA_AS_OF),
  ).results.map((res) => ({
    slug: pool.find((r) => r.id === res.id)!.slug, category: cat, score: res.score, rank: res.rank, signals: res.signals,
  })),
);
out.push(
  `delete from public.ranking_snapshots where period = 'all_time' and calculated_at = ${q(DATA_AS_OF)} and methodology_version = 'v1';`,
  `insert into public.ranking_snapshots (repository_id, period, category_id, calculated_at, ranking_score, rank, previous_rank, star_growth, signals, methodology_version) ` +
    `select r.id, 'all_time', c.id, ${q(DATA_AS_OF)}, x.score, x.rank, null, null, x.signals, 'v1' from jsonb_to_recordset(${j(rankingRows)}) as x(slug text, category text, score numeric, rank int, signals jsonb) ` +
    `join public.repositories r on r.slug = x.slug left join public.categories c on c.slug = x.category;`,
);

const file = join(process.cwd(), "supabase/seed.sql");
writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${file} (${out.length} lines)`);
